def main():
    meta = {}
    for i, m in enumerate(messages(), 1):
        meta[f"m{i:02d}"] = dict(id=f"m{i:02d}", from_name=m["frm"][0] or m["frm"][1], subject=m["subject"],
                                  date=m["date"].strftime("%d/%m %H:%M"))
    emails = {k: {**meta[k], **E[k]} for k in meta}
    assert set(E) == set(meta), "scenario table does not cover every email"
    for sid, site in SITES.items():
        if site["scenario"]:
            assert E[site["scenario"]]["truth"] == SCAM
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(dict(flag=FLAG, emails=emails, sites=SITES), ensure_ascii=False, indent=1), encoding="utf-8")
    (OUT.parent / "hosts.txt").write_text("\n".join(SITES) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(emails)} emails, {len(SITES)} sites")

if __name__ == "__main__":
    main()
